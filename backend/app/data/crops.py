def crop_list() -> list[dict]:
    """Lightweight list of crops for dropdowns."""
    return [
        {
            "key": key,
            "name": c["name"],
            "icon": c["icon"],
            "category": c["category"],
            "duration_days": c["duration_days"],
            "water_need": c["water_need"],
        }
        for key, c in CROPS.items()
    ]


def crop_stage(crop_key: str, days_since_planting: int) -> dict | None:
    crop = CROPS.get(crop_key)
    if not crop:
        return None
    for stage in crop["stages"]:
        if days_since_planting <= stage["to_day"]:
            return stage
    return crop["stages"][-1]
