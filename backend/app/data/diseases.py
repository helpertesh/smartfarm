def diagnose(crop_key: str, symptom_keys: list[str]) -> list[dict]:
    """Rank diseases for a crop by how many of the given symptoms they match."""
    results = []
    for d in DISEASES:
        if crop_key not in d["crops"]:
            continue
        matched = [s for s in symptom_keys if s in d["symptoms"]]
        if not matched:
            continue
        score = len(matched) / len(symptom_keys) if symptom_keys else 0
        results.append({**d, "matched_symptoms": matched, "confidence": round(score, 2)})
    results.sort(key=lambda r: (-r["confidence"], -len(r["matched_symptoms"])))
    return results
